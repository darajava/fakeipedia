import Link from "next/link";
import type { PaymentStatus } from "@/lib/billing-types";
import type { PaymentView } from "@/lib/payment-view";

export function PaymentNotices({ status, view }: { status: PaymentStatus; view: PaymentView }) {
  return <>
    {view.cancelled && (
      <p role="status">Checkout was cancelled. Your answer is still saved. Resume checkout or cancel the pending checkout below to start again.</p>
    )}
    {view.stage === "confirming" && (
      <p role="status">Checking your payment… Generation starts after payment is confirmed.</p>
    )}
    {view.stage === "terminal" && status.job && (
      <section aria-live="polite">
        <h2>{status.job.status === "superseded" ? "This article was generated by another reader" : "We couldn’t finish this article"}</h2>
        {status.job.funding !== "freebie" && <p>{view.refunded ? "Your payment has been refunded." : "Your payment is being refunded automatically."}</p>}
      </section>
    )}
    {view.refundPending && (
      <p role="status">
        Your refund is being processed.
        {view.refundNeedsAttention && " It needs another attempt; your payment remains recorded."}
      </p>
    )}
    {view.canRead && (
      <p><Link href={view.target}>Read the article</Link>{!status.job && " — no further payment is needed."}</p>
    )}
  </>;
}
